    /**
     * Load all passengers from server asynchronously.
     * Replaces the old JDBC scrollable ResultSet approach.
     */
    private void loadPassengers() {
        btnShowRecords.setEnabled(false);
        btnShowRecords.setText("Loading...");

        clientStub.findPassengers("", response -> {
            SwingUtilities.invokeLater(() -> {
                btnShowRecords.setEnabled(true);
                btnShowRecords.setText("Show All Records");

                if (response.isSuccess()) {
                    passengers = response.getPassengers();
                    currentIndex = passengers.isEmpty() ? -1 : 0;
                    if (!passengers.isEmpty()) {
                        displayRecord();
                    } else {
                        clearFields();
                        JOptionPane.showMessageDialog(this, "No records found.");
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to load passengers: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    clearFields();
                }
            });
        });
    }


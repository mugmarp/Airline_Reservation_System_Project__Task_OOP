    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
        String name = JOptionPane.showInputDialog(this, "Enter a name to Search:", "Find Passenger", JOptionPane.QUESTION_MESSAGE);
        if (name == null || name.trim().isEmpty()) {
            return;
        }

        btnFind.setEnabled(false);
        btnFind.setText("Searching...");

        clientStub.findPassengers(name.trim(), response -> {
            SwingUtilities.invokeLater(() -> {
                btnFind.setEnabled(true);
                btnFind.setText("Find");

                if (response.isSuccess()) {
                    passengers = response.getPassengers();
                    currentIndex = passengers.isEmpty() ? -1 : 0;
                    if (!passengers.isEmpty()) {
                        displayRecord();
                    } else {
                        clearFields();
                        JOptionPane.showMessageDialog(this, "No record found with Name: " + name);
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Search failed: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        });
    }//GEN-LAST:event_btnFindActionPerformed

    private void NextBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_NextBtnActionPerformed
        if (currentIndex < passengers.size() - 1) {
            currentIndex++;
            displayRecord();
        } else {
            JOptionPane.showMessageDialog(this, "Already at the last record.");
        }
    }//GEN-LAST:event_NextBtnActionPerformed


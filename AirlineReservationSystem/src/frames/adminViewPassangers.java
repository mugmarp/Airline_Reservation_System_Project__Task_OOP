    /**
     * Display the passenger at currentIndex in the form fields.
     * Replaces the old displayRecord() that read from ResultSet.
     */
    public void displayRecord() {
        if (currentIndex < 0 || currentIndex >= passengers.size()) {
            clearFields();
            return;
        }
        passenger p = passengers.get(currentIndex);
        
        txtFirstName.setText(p.getFirstName());
        txtPhone.setText(p.getPhoneNumber());
        txtPassport.setText(p.getPassportNumber());
        txtNationality.setText(p.getNationality());
        txtLastName.setText(p.getLastName());
        txtEmail.setText(p.getEmail());

        String gender = p.getGender();
        if (gender != null) {
            cmbGender.setSelectedItem(gender);
        } else {
            cmbGender.setSelectedItem("");
        }
        
        // Convert LocalDate to Date for JDateChooser
        if (p.getDateOfBirth() != null) {
            DOBChooser.setDate(java.sql.Date.valueOf(p.getDateOfBirth()));
        } else {
            DOBChooser.setDate(null);
        }

        txtFirstName.requestFocus();
    }

    /**
     * Clear all form fields.
     */
    private void clearFields() {
        txtFirstName.setText("");
        txtPhone.setText("");
        txtPassport.setText("");
        txtNationality.setText("");
        txtLastName.setText("");
        txtEmail.setText("");
        cmbGender.setSelectedIndex(0);
        DOBChooser.setDate(null);
        txtFirstName.requestFocus();
        currentIndex = -1;
    }


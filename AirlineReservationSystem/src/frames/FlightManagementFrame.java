    private void btnUpdateStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStatusActionPerformed
        int selectedRow = flightsTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a flight row first.");
            return;
        }

        String newStatus = cmbStatus.getSelectedItem().toString();
        int scheduleId = (int) tableModel.getValueAt(selectedRow, 0);

        btnUpdateStatus.setEnabled(false);
        btnUpdateStatus.setText("Updating...");

        clientStub.updateFlightStatus(scheduleId, newStatus, response -> {
            SwingUtilities.invokeLater(() -> {
                btnUpdateStatus.setEnabled(true);
                btnUpdateStatus.setText("Update Status");

                if (response.isSuccess()) {
                    // Update the UI table on success
                    tableModel.setValueAt(newStatus, selectedRow, 5);
                    JOptionPane.showMessageDialog(this, "✅ Status updated to: " + newStatus + "\n(Schedule ID: " + scheduleId + ")");
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to update status: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        });
    }//GEN-LAST:event_btnUpdateStatusActionPerformed


    private void loadFlights() {
        tableModel.setRowCount(0);
        btnRefresh.setEnabled(false);
        btnRefresh.setText("Loading...");

        clientStub.getAllFlights(response -> {
            SwingUtilities.invokeLater(() -> {
                btnRefresh.setEnabled(true);
                btnRefresh.setText("Refresh Table");

                if (response.isSuccess()) {
                    List<flight> flights = response.getFlights();
                    for (flight f : flights) {
                        tableModel.addRow(new Object[]{
                            f.getScheduleId(),
                            f.getFlightNumber(),
                            f.getOrigin(),
                            f.getDestination(),
                            f.getDepartureTime(),
                            "Scheduled" // this is the Default display status
                        });
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to load flights: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        });
    }


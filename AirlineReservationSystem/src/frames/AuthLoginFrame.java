    private void btnLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoginActionPerformed
        String username = txtAdminUsername.getText().trim();
        char[] passwordChars = txtPassword.getPassword();
        String password = new String(passwordChars);

        if (username.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both username and password!!!!!!", "Missing Info", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        // Use ClientStub to authenticate via server
        btnLogin.setEnabled(false);
        btnLogin.setText("Connecting...");
        
        clientStub.authenticate(username, password, response -> {
            SwingUtilities.invokeLater(() -> {
                btnLogin.setEnabled(true);
                btnLogin.setText("Login");
                
                if (response.isSuccess()) {
                    String role = response.getRole();
                    this.dispose();
                    
                    if ("Admin".equals(role)) {
                        JOptionPane.showMessageDialog(this, "Welcome, Administrator!!!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                        adminActions.Main();
                    } else {
                        JOptionPane.showMessageDialog(this, "Welcome, Agent!!!!!", "Login Successful", JOptionPane.INFORMATION_MESSAGE);
                        MainFrame.Main();
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Wrong username or password: " + response.getMessage(), "Access Denied", JOptionPane.ERROR_MESSAGE);
                    txtPassword.setText("");
                }
            });
        });
    }


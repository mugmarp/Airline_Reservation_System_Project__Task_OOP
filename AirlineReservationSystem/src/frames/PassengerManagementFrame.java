    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String passportQuery = txtSearchPassport.getText().trim().toUpperCase();
        if (passportQuery.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a passport number to search.");
            return;
        }

        tableModel.setRowCount(0);
        btnSearch.setEnabled(false);
        btnSearch.setText("Searching...");

        clientStub.findPassengers(passportQuery, response -> {
            SwingUtilities.invokeLater(() -> {
                btnSearch.setEnabled(true);
                btnSearch.setText("Search");

                if (response.isSuccess()) {
                    List<passenger> passengers = response.getPassengers();
                    boolean found = false;
                    for (passenger p : passengers) {
                        if (p.getPassportNumber().toUpperCase().contains(passportQuery)) {
                            tableModel.addRow(new Object[]{
                                p.getPassengerId(),
                                p.getFirstName(),
                                p.getLastName(),
                                p.getNationality(),
                                p.getPassportNumber()
                            });
                            found = true;
                        }
                    }
                    if (!found) {
                        JOptionPane.showMessageDialog(this, "No passengers found matching that passport.");
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Search failed: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        });
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = passengersTable.getSelectedRow();
        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this, "Please select a passenger row to delete.");
            return;
        }

        int passengerId = (int) tableModel.getValueAt(selectedRow, 0);
        String passport = (String) tableModel.getValueAt(selectedRow, 4);

        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete the record for Passport: " + passport + "?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            btnDelete.setEnabled(false);
            btnDelete.setText("Deleting...");

            clientStub.deletePassenger(passengerId, response -> {
                SwingUtilities.invokeLater(() -> {
                    btnDelete.setEnabled(true);
                    btnDelete.setText("Delete Selected");

                    if (response.isSuccess()) {
                        JOptionPane.showMessageDialog(this, "Passenger deleted successfully.");
                        btnViewAllActionPerformed(null); // Refresh the table
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to delete: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                });
            });
        }
    }//GEN-LAST:event_btnDeleteActionPerformed


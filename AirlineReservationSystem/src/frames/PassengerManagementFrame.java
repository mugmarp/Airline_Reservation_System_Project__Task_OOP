    private void btnViewAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewAllActionPerformed
        tableModel.setRowCount(0);
        btnViewAll.setEnabled(false);
        btnViewAll.setText("Loading...");

        clientStub.findPassengers("", response -> {
            SwingUtilities.invokeLater(() -> {
                btnViewAll.setEnabled(true);
                btnViewAll.setText("View All Passengers");

                if (response.isSuccess()) {
                    List<passenger> passengers = response.getPassengers();
                    for (passenger p : passengers) {
                        tableModel.addRow(new Object[]{
                            p.getPassengerId(),
                            p.getFirstName(),
                            p.getLastName(),
                            p.getNationality(),
                            p.getPassportNumber()
                        });
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to load passengers: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                }
            });
        });
    }//GEN-LAST:event_btnViewAllActionPerformed


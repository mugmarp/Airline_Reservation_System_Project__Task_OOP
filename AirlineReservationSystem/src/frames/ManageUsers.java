    private void DeleteBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteBtnActionPerformed
        if (currentIndex < 0 || currentIndex >= users.size()) {
            JOptionPane.showMessageDialog(this, "Please select a user to delete.");
            return;
        }
        
        User user = users.get(currentIndex);
        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to delete user: " + user.getUsername() + "?",
                "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {
            DeleteBtn.setEnabled(false);
            DeleteBtn.setText("Deleting...");

            clientStub.deleteUser(user.getUserId(), response -> {
                SwingUtilities.invokeLater(() -> {
                    DeleteBtn.setEnabled(true);
                    DeleteBtn.setText("Delete");

                    if (response.isSuccess()) {
                        JOptionPane.showMessageDialog(this, "User deleted successfully.");
                        loadUsers(); // Refresh the list
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to delete: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                });
            });
        }
    }//GEN-LAST:event_DeleteBtnActionPerformed


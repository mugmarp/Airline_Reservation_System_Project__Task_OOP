    /**
     * Load all users from server asynchronously.
     * Replaces the old JDBC scrollable ResultSet approach.
     */
    private void loadUsers() {
        SaveBtn.setEnabled(false);
        SaveBtn.setText("Loading...");

        clientStub.findUsers("", response -> {
            SwingUtilities.invokeLater(() -> {
                SaveBtn.setEnabled(true);
                SaveBtn.setText("Add & Save");

                if (response.isSuccess()) {
                    users = response.getUsers();
                    currentIndex = users.isEmpty() ? -1 : 0;
                    if (!users.isEmpty()) {
                        displayRecord();
                    } else {
                        clearFields();
                    }
                } else {
                    JOptionPane.showMessageDialog(this, "Failed to load users: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    clearFields();
                }
            });
        });
    }


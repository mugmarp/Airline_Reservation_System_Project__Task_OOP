    private void SaveBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SaveBtnActionPerformed
        String username = txtUsername.getText().trim();
        String fullName = txtFullName.getText().trim();
        String password = txtDefaultPassword.getText().trim();
        String role = (String) jComboBox1.getSelectedItem();

        if (username.isEmpty() || fullName.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Username, Full Name, and Password are required.", "Missing Info", JOptionPane.WARNING_MESSAGE);
            return;
        }

        SaveBtn.setEnabled(false);
        SaveBtn.setText("Saving...");

        // Check if we're editing an existing user or adding new
        if (currentIndex >= 0 && currentIndex < users.size()) {
            // Update existing user
            User user = users.get(currentIndex);
            clientStub.updateUser(user.getUserId(), password, fullName, role, response -> {
                SwingUtilities.invokeLater(() -> {
                    SaveBtn.setEnabled(true);
                    SaveBtn.setText("Add & Save");
                    if (response.isSuccess()) {
                        JOptionPane.showMessageDialog(this, "User updated successfully.");
                        loadUsers();
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to update: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                });
            });
        } else {
            // Add new user
            User newUser = new User(username, fullName, password, role);
            clientStub.addUser(newUser, response -> {
                SwingUtilities.invokeLater(() -> {
                    SaveBtn.setEnabled(true);
                    SaveBtn.setText("Add & Save");
                    if (response.isSuccess()) {
                        JOptionPane.showMessageDialog(this, "User added successfully with ID: " + response.getUserId());
                        loadUsers();
                    } else {
                        JOptionPane.showMessageDialog(this, "Failed to add: " + response.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
                    }
                });
            });
        }
    }//GEN-LAST:event_SaveBtnActionPerformed

